// Generates `src/gd/anim.ts` — the robot and spider skeletal animations.
//
// Source is the game's own data, straight out of the local Steam install:
//   steam-gd/Resources/objectDefinitions.plist   frame count, delay, looped
//   steam-gd/Resources/Robot_AnimDesc.plist      per-frame part transforms
//   steam-gd/Resources/Spider_AnimDesc.plist
//
// Both AnimDesc files begin with a stray CRLF before the XML declaration, which
// a strict plist reader rejects — the raw text is trimmed before parsing.
//
// Only the animations gameplay can reach are emitted. The editor/menu ones
// (idle01, idle02, run2, run3, skip, dash_loop, walk) are ~100 more robot frames
// that nothing in a level would ever show.
//
// Usage: node scripts/gen-anim.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { parsePlist } from "../src/engine/plist.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const res = join(root, "..", "steam-gd", "Resources");

const read = (name) => parsePlist(readFileSync(join(res, name), "utf8").trimStart());

/** animations a level can actually put on screen */
const WANTED = {
  Robot: ["run", "jump_start", "jump_loop", "fall_start", "fall_loop", "idle"],
  Spider: ["run", "fall_loop", "jump", "idle"],
};

/** `"{-7.5, -5.175}"` -> [-7.5, -5.175] */
function pair(s) {
  const m = /^\{\s*([-\d.eE]+)\s*,\s*([-\d.eE]+)\s*\}$/.exec(String(s));
  if (!m) throw new Error(`not a pair: ${s}`);
  return [Number(m[1]), Number(m[2])];
}

/** `"robot_01_03_001.png"` -> 3 — the body part `iconFrames(mode, idx, limb)` wants */
function limbOf(texture) {
  const m = /^(?:robot|spider)_\d+_(\d+)_001\.png$/.exec(texture);
  if (!m) throw new Error(`not a limb texture: ${texture}`);
  return Number(m[1]);
}

const round = (n) => Math.round(n * 1e4) / 1e4;

function build(name) {
  const defs = read("objectDefinitions.plist")[name];
  const desc = read(`${name}_AnimDesc.plist`);
  const container = desc.animationContainer;

  // `customID` "back01".. marks the far-side copies of a limb, which the game
  // draws darkened (GJRobotSprite::updateColors, m1 0x5080fc).
  const isBack = new Map();
  for (const t of Object.values(desc.usedTextures)) {
    isBack.set(String(t.tag), typeof t.customID === "string" && t.customID.startsWith("back"));
  }

  const out = {};
  for (const anim of WANTED[name]) {
    const def = defs.animations[anim];
    if (!def) throw new Error(`${name} has no animation ${anim}`);
    const single = def.singleFrame;
    const count = single ? 1 : Number(def.frames);
    const frames = [];
    for (let i = 1; i <= count; i++) {
      const key = single ?? `${name}_${anim}_${String(i).padStart(3, "0")}.png`;
      const frame = container[key];
      if (!frame) throw new Error(`missing frame ${key}`);
      const parts = Object.values(frame).map((sp) => {
        const [x, y] = pair(sp.position);
        const [sx, sy] = pair(sp.scale);
        const [fx, fy] = pair(sp.flipped);
        return {
          limb: limbOf(sp.texture),
          back: isBack.get(String(sp.tag)) === true,
          x: round(x), y: round(y), sx: round(sx), sy: round(sy),
          rot: round(Number(sp.rotation)),
          flipX: fx === 1, flipY: fy === 1,
          z: Number(sp.zValue),
        };
      });
      parts.sort((a, b) => a.z - b.z);
      frames.push(parts);
    }
    out[anim] = {
      delay: single ? 0 : Number(def.delay),
      looped: single ? false : def.looped === "1",
      frames,
    };
  }
  return out;
}

const robot = build("Robot");
const spider = build("Spider");

const fmt = (p) => `{l:${p.limb},b:${p.back ? 1 : 0},x:${p.x},y:${p.y},`
  + `sx:${p.sx},sy:${p.sy},r:${p.rot}`
  + `${p.flipX ? ",fx:1" : ""}${p.flipY ? ",fy:1" : ""}}`;

function emit(table) {
  const lines = [];
  for (const [name, a] of Object.entries(table)) {
    lines.push(`  ${JSON.stringify(name)}: { delay: ${a.delay}, looped: ${a.looped}, frames: [`);
    for (const f of a.frames) lines.push(`    [${f.map(fmt).join(",")}],`);
    lines.push("  ] },");
  }
  return lines.join("\n");
}

const counts = (t) => Object.entries(t)
  .map(([k, v]) => `${k} ${v.frames.length}`).join(", ");

const src = `// GENERATED by scripts/gen-anim.mjs — do not hand-edit.
//
// Robot and spider skeletal animation, read from the game's own
// \`objectDefinitions.plist\` and \`*_AnimDesc.plist\` in the local Steam install.
// Positions are in world units (1 cocos point = 1 world unit, since world size
// is \`hd pixels * 0.5\`); \`r\` is degrees CW, GD's convention, so the renderer
// negates it. Parts are pre-sorted by the source's zValue.
//
// robot: ${counts(robot)}
// spider: ${counts(spider)}

/** one body part in one frame */
export interface AnimPart {
  /** body part 1-4, the \`limb\` argument of \`iconFrames\` */
  l: number;
  /** 1 when this is the far-side copy, drawn behind and darkened */
  b: 0 | 1;
  x: number; y: number;
  sx: number; sy: number;
  /** degrees, CW positive */
  r: number;
  fx?: 1; fy?: 1;
}

export interface Anim {
  /** seconds per frame; 0 for a single-frame pose */
  delay: number;
  looped: boolean;
  frames: AnimPart[][];
}

export const ROBOT_ANIM: Record<string, Anim> = {
${emit(robot)}
};

export const SPIDER_ANIM: Record<string, Anim> = {
${emit(spider)}
};

/**
 * How much darker the far-side limbs are drawn — \`GJRobotSprite::updateColors\`
 * (m1 0x5080fc) picks 0.5 when \`m_iconType == 6\` (spider) and 0.7 otherwise.
 */
export const BACK_LIMB_TINT = { robot: 0.7, spider: 0.5 } as const;
`;

const out = join(root, "src", "gd", "anim.ts");
writeFileSync(out, src);
console.log(`wrote ${out}`);
console.log(`  robot:  ${counts(robot)}`);
console.log(`  spider: ${counts(spider)}`);
