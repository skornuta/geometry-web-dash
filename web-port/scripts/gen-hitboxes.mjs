// Generates src/gd/hitboxes.ts — the object-id -> real hitbox table.
//
// Source: OpenGD's Source/LongData.cpp (https://github.com/Open-GD/OpenGD,
// GPL-3.0), which carries `GameObject::_pHitboxes` (435 boxes) and
// `GameObject::_pHitboxRadius` (38 circle radii). As with object.json, the file
// is NOT vendored — it is downloaded on demand into data/ (gitignored) and only
// the derived table is committed. Re-run with `npm run gen:hitboxes`.
//
// **Earlier sessions of this port recorded "OpenGD's `_pHitboxes` is declared
// and never filled — there is no hitbox table to be had, stop looking". That is
// wrong.** It is declared in `Source/GameObject.h` and filled in
// `Source/LongData.cpp`, a file no earlier search opened, so every hazard box in
// this project was tuned by hand for two sessions against data that existed.
//
// Format in the source:
//     struct Hitbox { float h, w, x, y; };            // GameObject.h
//     ax::Rect rec = {hb.x, hb.y, hb.w, hb.h};        // GameObject.cpp:759
// so **the first number is the HEIGHT and the second the WIDTH** (easy to get
// backwards), and x/y are the rect's **bottom-left corner** relative to the
// object's position — which is centred for all but 15 of the 435 entries.
// GameObject.cpp then applies the object's rotation, scale and flips to that
// rect, which is why we store the centre offset and transform it the same way.
//
// Cross-checked against a Ghidra decompile of `GameObject::customSetup`
// (CallocGD/GD-2.206-Decompiled), which sets per-id `m_spriteWidthScale` /
// `m_spriteHeightScale`: id 8 (spike) is 0.2 x 0.4 of its 30x30 sprite = 6 x 12,
// exactly what this table says.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC_URL = "https://raw.githubusercontent.com/Open-GD/OpenGD/master/Source/LongData.cpp";
const DATA = path.join(ROOT, "data", "opengd-longdata.cpp");
const OUT = path.join(ROOT, "src", "gd", "hitboxes.ts");

if (!fs.existsSync(DATA)) {
  console.log(`downloading ${SRC_URL}`);
  const res = await fetch(SRC_URL);
  if (!res.ok) throw new Error(`fetch failed: ${res.status}`);
  fs.mkdirSync(path.dirname(DATA), { recursive: true });
  fs.writeFileSync(DATA, await res.text());
}
const src = fs.readFileSync(DATA, "utf8");

const boxSeg = src.slice(src.indexOf("_pHitboxes"), src.indexOf("_pHitboxRadius"));
const boxes = [...boxSeg.matchAll(
  /\{(\d+),\s*\{(-?[\d.]+),\s*(-?[\d.]+),\s*(-?[\d.]+),\s*(-?[\d.]+)\}\}/g)]
  .map(([, id, h, w, x, y]) => ({
    id: +id, h: +h, w: +w, x: +x, y: +y,
  }));

const radiusSeg = src.slice(src.indexOf("_pHitboxRadius"), src.indexOf("_pBlocks"));
const radii = [...radiusSeg.matchAll(/\{(\d+),\s*([\d.]+)\}/g)]
  .map(([, id, r]) => ({ id: +id, r: +r }));

if (boxes.length < 400 || radii.length < 30) {
  throw new Error(`parsed only ${boxes.length} boxes / ${radii.length} radii — format changed?`);
}

// 2.2 objects the 2.1-era table does not have, each pinned by a native run
// (otherwise they fall back to their sprite's size, which is not the hitbox):
//   1933 swing portal — Dash f3878-3879: the real player's box reaches it
//        between x = 4624.09 and 4624.41, so it is 33.2-33.8 wide; 33.5 (the
//        middle) keeps the run frame-exact through the portal to f4375. Height
//        as every other gamemode portal (the sprite would give 44.5 x 85.5).
//   3004 spider orb — 36 x 36 like every other orb (not yet pinned by a run).
const EXTRA_22 = [
  { id: 1933, w: 33.5, h: 86, x: -16.75, y: -43 },
  { id: 3004, w: 36, h: 36, x: -18, y: -18 },
  // APPROXIMATION: 747's box (same TeleportPortalObject class; the table has
  // no row for 2902)
  { id: 2902, w: 25, h: 90, x: 12 - 12.5, y: -45 },
];
for (const e of EXTRA_22) if (!boxes.some((b) => b.id === e.id)) boxes.push({ ...e });
boxes.sort((a, b) => a.id - b.id);

// centre offset from the object's position: the stored rect's bottom-left plus
// half its size. Zero for all but 15 ids.
const rows = boxes.map((b) => {
  const dx = b.x + b.w / 2;
  const dy = b.y + b.h / 2;
  return `  [${b.id}, { w: ${b.w}, h: ${b.h}`
    + (dx || dy ? `, dx: ${dx}, dy: ${dy}` : "")
    + " }],";
});

const out = `// GENERATED by scripts/gen-hitboxes.mjs — do not hand-edit.
//
// The real per-object hitbox table, from OpenGD's Source/LongData.cpp
// (\`GameObject::_pHitboxes\` / \`_pHitboxRadius\`). ${boxes.length} boxes, ${radii.length} radii.
//
// \`w\`/\`h\` are the hitbox size in world units **before** the object's own scale
// property; \`dx\`/\`dy\` offset its centre from the object's position, in the
// object's own unrotated, unflipped frame (present for only ${
  boxes.filter((b) => b.x + b.w / 2 || b.y + b.h / 2).length} of the ${boxes.length}).
// A \`radius\` entry means the object collides as a **circle** of that radius,
// which takes precedence over the box.
export interface HitboxDef {
  w: number;
  h: number;
  dx?: number;
  dy?: number;
}

export const HITBOXES = new Map<number, HitboxDef>([
${rows.join("\n")}
]);

/** ids that collide as a circle (saws, blades, cogwheels) */
export const HITBOX_RADII = new Map<number, number>([
${radii.map((r) => `  [${r.id}, ${r.r}],`).join("\n")}
]);
`;

fs.writeFileSync(OUT, out);
console.log(`wrote ${OUT}: ${boxes.length} boxes, ${radii.length} radii`);
