// Generates `src/gd/beasts.ts` — how the animated monsters (GJBeast01–05)
// are put together from their parts.
//
// Source is the game's own data, from the local Steam install:
//   steam-gd/Resources/objectDefinitions.plist   each monster's default animation
//   steam-gd/Resources/GJBeast0N_AnimDesc.plist  per-frame part transforms
//
// An `AnimatedGameObject` with `usePA` draws its frames as several part
// sprites (`usedTextures`), placed per frame by the AnimDesc. The object table
// (OpenGD) gives each monster only one part — GJBeast01 drew as a lone black
// crest where the game shows the whole head and jaw (Geometrical Dominator
// 50%, 2.2 playthrough YouTube g3_XUbK-PP0).
//
// Usage: node scripts/gen-beasts.mjs
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { parsePlist } from "../src/engine/plist.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const res = join(root, "..", "steam-gd", "Resources");
const read = (name) => parsePlist(readFileSync(join(res, name), "utf8").trimStart());

/** object id -> the monster it is (the id table's main frames) */
const IDS = { 918: "GJBeast01", 1327: "GJBeast02", 1328: "GJBeast03", 1584: "GJBeast04", 2012: "GJBeast05" };

const pair = (s) => {
  const m = /^\{\s*([-\d.eE]+)\s*,\s*([-\d.eE]+)\s*\}$/.exec(String(s));
  if (!m) throw new Error(`not a pair: ${s}`);
  return [Number(m[1]), Number(m[2])];
};
const round = (n) => Math.round(n * 1e4) / 1e4;

const sheet = readFileSync(join(root, "public", "assets", "FireSheet_01-hd.plist"), "utf8");
const hasFrame = (f) => sheet.includes(`<key>${f}</key>`);

const defs = read("objectDefinitions.plist");
const out = {};
for (const [id, name] of Object.entries(IDS)) {
  const def = defs[name];
  const descFile = `${name}_AnimDesc.plist`;
  if (!def || !existsSync(join(res, descFile))) throw new Error(`no data for ${name}`);
  const anim = def.defaultAnimation;
  const meta = def.animations[anim];
  const desc = read(descFile).animationContainer;
  const frames = [];
  for (let k = 1; k <= Number(meta.frames); k++) {
    const f = desc[`${name}_${anim}_${String(k).padStart(3, "0")}.png`];
    if (!f) throw new Error(`${name} ${anim} frame ${k} missing`);
    const parts = Object.values(f).map((s) => {
      const [x, y] = pair(s.position);
      const [sx, sy] = pair(s.scale);
      const [flx, fly] = pair(s.flipped);
      const glow = s.texture.replace(/_001\.png$/, "_glow_001.png");
      return {
        frame: s.texture, glow: hasFrame(glow) ? glow : null,
        x: round(x), y: round(y), sx: round(sx), sy: round(sy),
        rot: round(Number(s.rotation)), flipX: flx !== 0, flipY: fly !== 0, z: Number(s.zValue),
      };
    }).sort((a, b) => a.z - b.z);
    frames.push(parts);
  }
  out[id] = { name, anim, delay: Number(meta.delay), looped: meta.looped === "1", frames };
}

const body = `// GENERATED by scripts/gen-beasts.mjs from the game's objectDefinitions.plist
// and GJBeast0N_AnimDesc.plist — do not edit by hand.

export interface BeastPart {
  frame: string;
  /** the part's \`_glow\` frame, when the sheet has one */
  glow: string | null;
  /** world units from the object's centre */
  x: number; y: number;
  sx: number; sy: number;
  /** degrees, clockwise */
  rot: number;
  flipX: boolean; flipY: boolean;
  z: number;
}

export interface BeastAnim {
  name: string;
  /** the default animation the object plays */
  anim: string;
  delay: number;
  looped: boolean;
  /** per frame, its parts back to front */
  frames: BeastPart[][];
}

export const BEASTS: ReadonlyMap<number, BeastAnim> = new Map(Object.entries(${JSON.stringify(out)}).map(([k, v]) => [Number(k), v as BeastAnim]));
`;
writeFileSync(join(root, "src", "gd", "beasts.ts"), body);
console.log(Object.entries(out).map(([id, v]) => `${id} ${v.name} ${v.anim} ${v.frames.length}f parts ${v.frames[0].length}`).join("\n"));
