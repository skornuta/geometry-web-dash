// Generates src/gd/nativeGeometry.ts — where the real game draws each object's
// sprites, read out of the running game rather than inferred from OpenGD.
//
//   node scripts/gen-native-geometry.mjs
//
// Input: data/native-geometry.jsonl, one line per object id, dumped by the
// gd-ui-capture Geode mod's `geometry` command from every one of the 22 levels
// (see scripts/native-cmd.mjs). Each line is the object's content box, where
// its texture rect sits in it, and the same for each child sprite.
//
// The port places a main sprite by the atlas offset about the frame's *source*
// size, and children by OpenGD's positions measured from that same source box.
// The game does neither: it lays every object out in its own content box
// (30x30 for a block whose strip texture is only 30x20), so both land in the
// wrong place whenever the two boxes differ — the white edge of
// block008_topcolor sat 5 units low, inside its own block. This table holds
// the difference for the main sprite and the game's own offsets for children.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { OBJECT_DEFS } from "../src/gd/objects.ts";
import { parseAtlas } from "../src/engine/atlas.ts";
import { SHEET_FILES } from "../src/gd/sheets.ts";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "src", "gd", "nativeGeometry.ts");
/**
 * Below this (world units) the two layouts agree. The game runs the -uhd
 * sheet and the port the -hd one, whose trims round differently by up to half
 * a unit; anything smaller than a unit is that rounding, not a layout error.
 */
const TOL = 1;

const atlas = new Map();
for (const f of new Set(Object.values(SHEET_FILES))) {
  const p = path.join(ROOT, "public", "assets", `${f}.plist`);
  if (!fs.existsSync(p)) continue;
  for (const [n, fr] of parseAtlas(fs.readFileSync(p, "utf8"))) if (!atlas.has(n)) atlas.set(n, fr);
}
const native = new Map();
for (const line of fs.readFileSync(path.join(ROOT, "data", "native-geometry.jsonl"), "utf8").split("\n")) {
  if (!line.trim()) continue;
  const g = JSON.parse(line);
  if (!native.has(g.id)) native.set(g.id, g);
}

const r2 = (v) => Math.round(v * 100) / 100;
const main = [], kids = [];
for (const [id, g] of [...native].sort((a, b) => a[0] - b[0])) {
  const def = OBJECT_DEFS.get(id);
  if (!def) continue;
  const fr = atlas.get(def.frame);
  const s = g.self;
  // Compare like with like: an animated object may be showing another frame
  // of its sequence in the dump, whose trim is different.
  const sameFrame = fr && s.rw !== undefined
    && Math.abs(s.rw - fr.w / 2) < 1 && Math.abs(s.rh - fr.h / 2) < 1;
  if (sameFrame) {
    // texture centre about the content box's centre; cocos mirrors the offset
    // of a flipped sprite, so undo that for a flipped first instance
    let nx = s.ox + s.rw / 2 - s.w / 2, ny = s.oy + s.rh / 2 - s.h / 2;
    if (s.fx) nx = -nx;
    if (s.fy) ny = -ny;
    const dx = nx - fr.offsetX / 2, dy = ny - fr.offsetY / 2;
    if (Math.hypot(dx, dy) > TOL) main.push(`  [${id}, [${r2(dx)}, ${r2(dy)}]],`);
  }
  // children: only where the game and the table agree on how many there are,
  // matched in z order, and only from an unflipped first instance
  const ours = (def.children ?? []);
  const theirs = g.children.filter((c) => c.rw !== undefined)
    .map((c, i) => ({ ...c, i })).sort((a, b) => a.z - b.z || a.i - b.i);
  if (!ours.length || ours.length !== theirs.length || s.fx || s.fy) continue;
  const offs = theirs.map((c) => {
    // Node position locates its anchor, not its center. In particular the
    // four quarters of 1888 all sit at (0,0), anchor (1,0), and mirror about
    // that corner. Centering all four there turns the circular glow square.
    const ax = (0.5 - c.ax) * c.w * c.sx;
    const ay = (0.5 - c.ay) * c.h * c.sy;
    const angle = -c.rot * Math.PI / 180;
    const cos = Math.cos(angle), sin = Math.sin(angle);
    return [r2(c.x - s.w / 2 + ax * cos - ay * sin),
      r2(c.y - s.h / 2 + ax * sin + ay * cos)];
  });
  if (offs.some(([x, y], i) => Math.hypot(x - ours[i].dx, y - ours[i].dy) > TOL)) {
    kids.push(`  [${id}, ${JSON.stringify(offs)}],`);
  }
}

fs.writeFileSync(OUT, `// GENERATED by scripts/gen-native-geometry.mjs from data/native-geometry.jsonl
// (dumped from the running game by the gd-ui-capture mod) — do not edit by hand.

/**
 * Where the game draws an object's main sprite, relative to where the atlas
 * offset alone puts it: add this (object-local, before flip and rotation).
 */
export const MAIN_SPRITE_FIX: ReadonlyMap<number, readonly [number, number]> = new Map([
${main.join("\n")}
]);

/**
 * The game's own offset for each child sprite from the object's centre, in the
 * same z order as \`ObjectDef.children\` — used in place of the table's dx/dy.
 */
export const CHILD_OFFSETS: ReadonlyMap<number, readonly (readonly [number, number])[]> = new Map([
${kids.join("\n")}
]);
`);
console.log(`${OUT}: ${main.length} main-sprite fixes, ${kids.length} objects with child offsets`);
